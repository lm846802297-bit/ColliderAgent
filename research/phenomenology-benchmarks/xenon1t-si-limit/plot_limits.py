import csv,glob,numpy as np, matplotlib.pyplot as plt
plt.rcParams.update({'font.size':10,'axes.spines.top':False,'axes.spines.right':False,'pdf.fonttype':42})
d=np.genfromtxt('limits.csv',delimiter=',',names=True)
orig=glob.glob('xenon*-1.0.0/xe_likelihood/data/ancillary_data/xenon1t_1ty.csv')
r=np.array([[float(a),float(b)] for a,b,*_ in csv.reader(open(orig[0])) if a and a[0].isdigit()])
x=d['m_chi_GeV']; y=d['independent_toy_cm2']
fig,(a,b)=plt.subplots(1,2,figsize=(9.2,4.35))
fig.subplots_adjust(left=.11,right=.976,bottom=.22,top=.74,wspace=.33)
fig.text(.11,.93,'XENON1T nuclear-recoil limit from a heavy-vector model',fontsize=15,weight='bold')
fig.text(.11,.865,'Observed 90% CL  |  Spin-independent elastic scattering  |  Public binwise likelihood',color='#48566a')
a.loglog(x,y,color='#007481',lw=2.25,label='Recomputed, toy threshold')
a.loglog(x,d['independent_asymptotic_cm2'],color='#bc652b',lw=1.65,ls='--',label='Recomputed, asymptotic')
a.scatter(*r.T,s=14,facecolors='white',edgecolors='#414d5e',linewidths=.8,label='2018 full likelihood (reference)',zorder=5)
a.legend(loc='upper right',fontsize=7.2,frameon=False)
a.set_ylabel(r'WIMP–proton cross section  $\sigma_p^{90}$ [cm$^2$]')
b.loglog(x,d['C90_GeVminus2'],color='#007481',lw=2.25)
b.set_ylabel(r'$|g_\chi g_N|/m_V^2$  upper limit  [GeV$^{-2}$]')
a.set_title('A. Cross-section limit',loc='left',weight='bold',pad=11)
b.set_title('B. Contact-interaction limit',loc='left',weight='bold',pad=11)
for j in [a,b]:
 j.set_xlabel(r'Dark matter mass  $m_\chi$ [GeV]');j.set_xlim(6,1000)
 j.grid(True,which='major',alpha=.18)
fig.text(.11,.072,'Source: XENON Collaboration, arXiv:2210.07231, Fig. 5a and v1.0.0 public release.',fontsize=8,color='#48566a')
fig.text(.11,.040,'Isoscalar coupling, standard halo, heavy mediator. Not a limit for inelastic or radiative scattering.',fontsize=8,color='#48566a')
fig.savefig('PhenoAgent_XENON1T_SI_90CL.pdf',metadata={'CreationDate':None,'ModDate':None})
